function pruneTickHistory(value, referenceTs = Date.now()) {
  const cutoff = Number(referenceTs) - TICK_HISTORY_RETENTION_MS;
  return (Array.isArray(value) ? value : [])
    .map(tick => ({ ts:Number(tick?.ts), price:Number(tick?.price) }))
    .filter(tick => Number.isFinite(tick.ts) && Number.isFinite(tick.price) && tick.ts >= cutoff)
    .sort((left, right) => left.ts - right.ts)
    .slice(-TICK_HISTORY_MAX);
}

function appendTickHistory(history, tick) {
  // signal.createdAt is generated by this Worker, so use the local receipt
  // time for tick ordering instead of the provider's minute-level timestamp.
  const normalized = { ts:Number(tick?.receivedAt ?? tick?.ts), price:Number(tick?.price) };
  if (!Number.isFinite(normalized.ts) || !Number.isFinite(normalized.price)) {
    return Array.isArray(history) ? history : [];
  }
  const ticks = Array.isArray(history) ? [...history, normalized] : [normalized];
  const cutoff = normalized.ts - TICK_HISTORY_RETENTION_MS;
  let first = 0;
  while (first < ticks.length && ticks[first].ts < cutoff) first += 1;
  return ticks.slice(Math.max(first, ticks.length - TICK_HISTORY_MAX));
}

function normalizedExposureSignal(value) {
  const tf=String(value?.tf||'');
  const side=String(value?.side||'');
  const id=String(value?.id||'');
  if (!id||!SIGNAL_TIMEFRAMES.includes(tf)||!['buy','sell'].includes(side)) return null;
  return {
    id,tf,side,conf:Number.isFinite(Number(value?.conf))?Number(value.conf):0,
    signalBarTs:Number(value?.signalBarTs)||0,createdAt:Number(value?.createdAt)||0,
    status:String(value?.status||'')
  };
}

function compareExposureCandidates(left,right) {
  const confidence=Number(right?.conf||0)-Number(left?.conf||0);
  if (confidence) return confidence;
  const timeframe=Number(GOLD_EXPOSURE_TF_RANK[right?.tf]||0)-Number(GOLD_EXPOSURE_TF_RANK[left?.tf]||0);
  if (timeframe) return timeframe;
  const barTime=Number(right?.signalBarTs||0)-Number(left?.signalBarTs||0);
  return barTime||String(left?.id||'').localeCompare(String(right?.id||''));
}

function appendExposureRecord(records,record) {
  const list=Array.isArray(records)?records.filter(item=>item?.signalId!==record.signalId):[];
  return [...list,record].slice(-GOLD_EXPOSURE_MAX_RECORDS);
}

function activeExposureFromSignal(signal,now,source='admission') {
  return {
    symbol:'XAUUSD',status:'active',side:signal.side,maxPositions:1,
    primarySignalId:signal.id,primaryTf:signal.tf,openedAt:Number(signal.createdAt)||now,
    updatedAt:now,cooldownUntil:0,closeReason:'',closedAt:0,
    confirmations:[],blocked:[],source
  };
}

function closeGoldExposure(state,status,now) {
  const stopped=status==='stopped';
  return {
    ...state,status:stopped?'cooldown':'flat',updatedAt:now,closedAt:now,
    closeReason:stopped?'sl':status,cooldownUntil:stopped?now+GOLD_EXPOSURE_COOLDOWN_MS:0,
    lastPrimarySignalId:state.primarySignalId,lastPrimaryTf:state.primaryTf,
    primarySignalId:'',primaryTf:'',side:''
  };
}

function canonicalTelegramEvent(event) {
  const value=String(event||'');
  if (value==='created'||value==='new_signal'||value==='manual') return 'new_signal';
  if (value==='stopped'||value==='sl') return 'sl';
  if (['confirmation','tp1','tp2','expired','news'].includes(value)) return value;
  return '';
}

function telegramEventStorageKey(eventId) {
  return `${TELEGRAM_EVENT_PREFIX}${String(eventId)}`;
}

function telegramCursorStorageKey(rootSignalId) {
  return `${TELEGRAM_CURSOR_PREFIX}${String(rootSignalId)}`;
}

function telegramEventSequence(value) {
  return {
    eventAt:Number(value?.eventAt)||0,
    rank:Number.isFinite(Number(value?.rank))
      ? Number(value.rank)
      : Number(TELEGRAM_EVENT_RANK[value?.kind]||0),
    eventId:String(value?.eventId||'')
  };
}

function compareTelegramSequence(left,right) {
  const a=telegramEventSequence(left),b=telegramEventSequence(right);
  return a.eventAt-b.eventAt||a.rank-b.rank||a.eventId.localeCompare(b.eventId);
}

function telegramEventTerminal(status) {
  return ['sent','dropped','failed','failed_ambiguous'].includes(String(status||''));
}

function makeTelegramEventRecord(signal,event,text,options={}) {
  const kind=canonicalTelegramEvent(event);
  const signalId=String(signal?.id||'');
  if (!kind||!signalId) return null;
  const rootSignalId=String(options.rootSignalId||options.primarySignalId||signalId);
  const eventAt=Number(options.eventAt)||(
    kind==='new_signal'?Number(signal?.createdAt):
    ['tp2','sl','expired'].includes(kind)?Number(signal?.closedAt||signal?.updatedAt):
    Number(signal?.updatedAt||signal?.createdAt)
  )||Date.now();
  const eventId=kind==='confirmation'
    ? `trade:${rootSignalId}:confirmation:${signalId}`
    : kind==='news'
      ? `news:${signalId}`
      : `trade:${signalId}:${kind}`;
  const now=Date.now();
  return {
    schema:TELEGRAM_EVENT_SCHEMA,eventId,rootSignalId,signalId,
    tf:String(signal?.tf||''),kind,event:kind,status:'pending',attempts:0,
    eventAt,signalCreatedAt:Number(options.signalCreatedAt||signal?.createdAt)||0,
    queuedAt:now,createdAt:now,updatedAt:now,nextAttemptAt:now,
    queuedVersion:APP_VERSION,text:String(text||'')
  };
}

function decideGoldExposure(previous,input={}) {
  const now=Number(input.now)||Date.now();
  const officialSignals=(Array.isArray(input.officialSignals)?input.officialSignals:[])
    .map(normalizedExposureSignal).filter(Boolean);
  const candidates=(Array.isArray(input.candidates)?input.candidates:[])
    .map(normalizedExposureSignal).filter(Boolean);
  let state=previous&&typeof previous==='object'?{...previous}:null;
  let justClosed=false;

  if (state?.status==='active'&&state.primarySignalId) {
    const primary=officialSignals.find(signal=>signal.id===state.primarySignalId);
    if (primary&&['tp2','stopped','expired'].includes(primary.status)) {
      state=closeGoldExposure(state,primary.status,now);
      justClosed=true;
    } else {
      state={...state,updatedAt:now};
    }
  }
  if (state?.status==='cooldown'&&now>=Number(state.cooldownUntil||0)) {
    state={...state,status:'flat',updatedAt:now,cooldownUntil:0};
  }

  // On the first deployment, fold already-open timeframe signals into one
  // market exposure without rewriting their historical TP/SL state.
  if (!state) {
    const activeOfficial=officialSignals
      .filter(signal=>GOLD_EXPOSURE_TIMEFRAMES.includes(signal.tf)&&['active','tp1'].includes(signal.status))
      .sort(compareExposureCandidates);
    if (activeOfficial.length) {
      const primary=activeOfficial[0];
      state=activeExposureFromSignal(primary,now,'bootstrap');
      for (const signal of activeOfficial.slice(1)) {
        const record={signalId:signal.id,tf:signal.tf,side:signal.side,conf:signal.conf,observedAt:now,source:'bootstrap'};
        if (signal.side===primary.side) state.confirmations=appendExposureRecord(state.confirmations,record);
        else state.blocked=appendExposureRecord(state.blocked,{...record,reason:'opposite'});
      }
    } else {
      state={symbol:'XAUUSD',status:'flat',side:'',maxPositions:1,primarySignalId:'',primaryTf:'',openedAt:0,updatedAt:now,closedAt:0,closeReason:'',cooldownUntil:0,confirmations:[],blocked:[],source:'initialized'};
    }
  }

  const decisions=[];
  const decideAgainstActive=candidate=>{
    const sameDirection=candidate.side===state.side;
    const decision=sameDirection?'confirmation':'blocked_opposite';
    const record={signalId:candidate.id,tf:candidate.tf,side:candidate.side,conf:candidate.conf,observedAt:now,source:'candidate'};
    if (sameDirection) state.confirmations=appendExposureRecord(state.confirmations,record);
    else state.blocked=appendExposureRecord(state.blocked,{...record,reason:'opposite'});
    decisions.push({signalId:candidate.id,tf:candidate.tf,decision,primarySignalId:state.primarySignalId});
  };

  if (state.status==='active') {
    for (const candidate of candidates) decideAgainstActive(candidate);
  } else if (state.status==='cooldown'&&now<Number(state.cooldownUntil||0)) {
    for (const candidate of candidates) {
      const decision=candidate.tf==='1m'?'informational_cooldown':'blocked_cooldown';
      state.blocked=appendExposureRecord(state.blocked,{
        signalId:candidate.id,tf:candidate.tf,side:candidate.side,conf:candidate.conf,
        observedAt:now,source:'candidate',reason:'cooldown'
      });
      decisions.push({signalId:candidate.id,tf:candidate.tf,decision,cooldownUntil:state.cooldownUntil});
    }
  } else {
    const eligible=candidates.filter(candidate=>GOLD_EXPOSURE_TIMEFRAMES.includes(candidate.tf)).sort(compareExposureCandidates);
    const winner=eligible[0]||null;
    if (winner) {
      state=activeExposureFromSignal({...winner,createdAt:now},now,justClosed?'post-close':'admission');
      decisions.push({signalId:winner.id,tf:winner.tf,decision:'accepted',primarySignalId:winner.id});
      for (const candidate of candidates) {
        if (candidate.id===winner.id) continue;
        decideAgainstActive(candidate);
      }
    } else {
      for (const candidate of candidates) {
        decisions.push({signalId:candidate.id,tf:candidate.tf,decision:'informational'});
      }
    }
  }

  state={...state,updatedAt:now,maxPositions:1};
  return {state,decisions};
}

/**
 * One coordination point for XAU/USD. It owns the single Twelve Data
 * connection, fans normalized quotes out to every browser, and persists only
 * completed one-minute candles. Critical state is stored before it is exposed.
 */
export class GoldFeed extends DurableObject {
  constructor(ctx, env) {
    super(ctx, env);
    this.upstream = null;
    this.connecting = false;
    this.latestQuote = null;
    this.currentBar = null;
    this.tickHistory = [];
    this.lastSnapshotWriteAt = 0;
    this.schemaReady = false;
    this.telegramDrainPromise = null;
    this.telegramDrainRequested = false;
    this.ctx.blockConcurrencyWhile(async () => {
      const stored = await this.ctx.storage.get(['latestQuote', 'currentBar', 'tickHistory']);
      this.latestQuote = stored.get('latestQuote') || null;
      this.currentBar = stored.get('currentBar') || null;
      this.tickHistory = pruneTickHistory(stored.get('tickHistory'), Date.now());
      const alarm = await this.ctx.storage.getAlarm();
      if (alarm == null) await this.ctx.storage.setAlarm(Date.now() + 1000);
    });
  }

  async fetch(request) {
    if ((request.headers.get('Upgrade') || '').toLowerCase() !== 'websocket') {
      return Response.json(await this.status());
    }
    await this.ensureProvider();
    const pair = new WebSocketPair();
    const [client, server] = Object.values(pair);
    this.ctx.acceptWebSocket(server);
    if (this.latestQuote) server.send(JSON.stringify(this.latestQuote));
    return new Response(null, { status: 101, webSocket: client });
  }

  async status() {
    return {
      ok: Boolean(this.latestQuote),
      provider: 'twelve-data',
      connected: this.upstream?.readyState === 1,
      latestQuote: this.latestQuote,
      currentBar: this.currentBar,
      clients: this.ctx.getWebSockets().length
    };
  }

  async ticks(options = {}) {
    const to = Number.isFinite(Number(options.to)) ? Number(options.to) : Date.now();
    const requestedFrom = Number.isFinite(Number(options.from)) ? Number(options.from) : to - 5 * 60_000;
    const from = Math.max(requestedFrom, to - TICK_HISTORY_RETENTION_MS);
    const limit = Math.max(1, Math.min(TICK_HISTORY_QUERY_MAX, Number(options.limit) || 600));
    this.tickHistory = pruneTickHistory(this.tickHistory, Date.now());
    const ticks = this.tickHistory
      .filter(tick => tick.ts >= from && tick.ts <= to)
      .slice(-limit);
    return {
      ok: true,
      provider: 'twelve-data',
      retentionMs: TICK_HISTORY_RETENTION_MS,
      maxTicks: TICK_HISTORY_MAX,
      from,
      to,
      count: ticks.length,
      ticks
    };
  }

  async manageGoldExposure(input = {}) {
    return this.ctx.storage.transaction(async transaction => {
      const previous=await transaction.get(GOLD_EXPOSURE_KEY);
      const result=decideGoldExposure(previous,input);
      await transaction.put(GOLD_EXPOSURE_KEY,result.state);
      return result;
    });
  }

  async goldExposureStatus() {
    const state=await this.ctx.storage.get(GOLD_EXPOSURE_KEY);
    return state||{
      symbol:'XAUUSD',status:'flat',side:'',maxPositions:1,
      primarySignalId:'',primaryTf:'',cooldownUntil:0
    };
  }

  async cancelGoldExposureReservation(input = {}) {
    const signalId=String(input.signalId||'');
    const now=Number(input.now)||Date.now();
    return this.ctx.storage.transaction(async transaction => {
      const state=await transaction.get(GOLD_EXPOSURE_KEY);
      if (!state||state.status!=='active'||state.primarySignalId!==signalId) return state||null;
      const cancelled={
        ...state,status:'flat',side:'',primarySignalId:'',primaryTf:'',
        updatedAt:now,closedAt:now,closeReason:'admission_failed',cooldownUntil:0,
        lastPrimarySignalId:signalId
      };
      await transaction.put(GOLD_EXPOSURE_KEY,cancelled);
      return cancelled;
    });
  }

  async queueTelegramEvent(input = {}) {
    const eventId=String(input?.eventId||'');
    const rootSignalId=String(input?.rootSignalId||'');
    const kind=canonicalTelegramEvent(input?.kind||input?.event);
    if (!eventId||!rootSignalId||!kind||!Number.isFinite(Number(input?.eventAt))) {
      return {ok:false,error:'invalid_telegram_event'};
    }
    const key=telegramEventStorageKey(eventId);
    await this.ctx.storage.transaction(async transaction => {
      const existing=await transaction.get(key);
      if (existing) return;
      const now=Date.now();
      await transaction.put(key,{
        ...input,schema:TELEGRAM_EVENT_SCHEMA,eventId,rootSignalId,kind,event:kind,
        status:'pending',attempts:0,queuedAt:Number(input.queuedAt)||now,
        createdAt:Number(input.createdAt)||now,updatedAt:now,nextAttemptAt:now,
        queuedVersion:String(input.queuedVersion||APP_VERSION)
      });
    });
    await this.drainTelegramEvents();
    return await this.ctx.storage.get(key);
  }

  async processTelegramEvents() {
    await this.drainTelegramEvents();
    return {ok:true};
  }

  async drainTelegramEvents() {
    this.telegramDrainRequested=true;
    if (this.telegramDrainPromise) return this.telegramDrainPromise;
    this.telegramDrainPromise=(async()=>{
      while (this.telegramDrainRequested) {
        this.telegramDrainRequested=false;
        await this.drainTelegramEventsOnce();
      }
    })().finally(()=>{ this.telegramDrainPromise=null; });
    return this.telegramDrainPromise;
  }

  async drainTelegramEventsOnce() {
    const listed=await this.ctx.storage.list({prefix:TELEGRAM_EVENT_PREFIX,limit:1000});
    const groups=new Map();
    for (const [key,record] of listed) {
      if (!record||typeof record!=='object') continue;
      const root=String(record.rootSignalId||record.signalId||'');
      if (!root) continue;
      if (!groups.has(root)) groups.set(root,[]);
      groups.get(root).push({key,record});
    }
    const now=Date.now();
    for (const [root,items] of groups) {
      items.sort((left,right)=>compareTelegramSequence(left.record,right.record));
      let cursor=await this.ctx.storage.get(telegramCursorStorageKey(root));
      for (const item of items) {
        let record=item.record;
        if (telegramEventTerminal(record.status)) continue;
        let dropReason='';
        if (Number(record.schema)!==TELEGRAM_EVENT_SCHEMA) dropReason='legacy_schema';
        else if (String(record.queuedVersion||'')!==APP_VERSION) dropReason='previous_deployment';
        else if (now-Number(record.eventAt||0)>TELEGRAM_EVENT_MAX_AGE_MS) dropReason='stale_event';
        else if (record.status==='sending') dropReason='ambiguous_restart';
        else if (cursor&&compareTelegramSequence(record,cursor)<=0) dropReason='delayed_event';
        if (dropReason) {
          record={...record,status:'dropped',dropReason,updatedAt:now,nextAttemptAt:0};
          cursor=telegramEventSequence(record);
          await this.persistTelegramEvent(item.key,record,cursor);
          continue;
        }
        if (record.status!=='pending'||Number(record.nextAttemptAt||0)>now) break;

        const sending={...record,status:'sending',updatedAt:Date.now()};
        await this.ctx.storage.put(item.key,sending);
        const result=await sendTelegramText(this.env,sending.text);
        const attempts=Number(sending.attempts||0)+1;
        const completedAt=Date.now();
        if (result.ok) {
          record={
            ...sending,status:'sent',attempts,updatedAt:completedAt,sentAt:completedAt,
            nextAttemptAt:0,lastStatus:Number(result.status||0),lastError:'',dropReason:''
          };
          cursor=telegramEventSequence(record);
          await this.persistTelegramEvent(item.key,record,cursor);
          continue;
        }
        if (result.ambiguous) {
          record={
            ...sending,status:'failed_ambiguous',attempts,updatedAt:completedAt,nextAttemptAt:0,
            lastStatus:Number(result.status||0),lastError:String(result.error||'telegram_ambiguous'),
            dropReason:'ambiguous_delivery'
          };
          cursor=telegramEventSequence(record);
          await this.persistTelegramEvent(item.key,record,cursor);
          continue;
        }
        const exhausted=attempts>=TELEGRAM_MAX_ATTEMPTS;
        record={
          ...sending,status:exhausted?'failed':'pending',attempts,updatedAt:completedAt,
          lastStatus:Number(result.status||0),lastError:String(result.error||'telegram_api_error'),
          nextAttemptAt:exhausted?0:completedAt+telegramRetryDelayMs(attempts)
        };
        if (exhausted) {
          cursor=telegramEventSequence(record);
          await this.persistTelegramEvent(item.key,record,cursor);
          continue;
        }
        await this.persistTelegramEvent(item.key,record,null);
        console.error(JSON.stringify({
          message:'telegram delivery failed',eventId:record.eventId,signalId:record.signalId,
          event:record.kind,attempts,status:record.lastStatus,error:record.lastError
        }));
        break;
      }
    }
  }

  async persistTelegramEvent(key,record,cursor) {
    await this.ctx.storage.transaction(async transaction => {
      await transaction.put(key,record);
      if (cursor) await transaction.put(telegramCursorStorageKey(record.rootSignalId),cursor);
    });
    await persistTelegramDelivery(this.env,telegramDeliveryKeyFromEventId(record.eventId),record);
  }

  async ensureProvider() {
    if (!isTwelveDataConfigured(this.env)) return false;
    if (this.upstream?.readyState === 0 || this.upstream?.readyState === 1 || this.connecting) return true;
    this.connecting = true;
    try {
      const apiKey = String(this.env.TWELVE_DATA_API_KEY).trim();
      const socket = new WebSocket(`wss://ws.twelvedata.com/v1/quotes/price?apikey=${encodeURIComponent(apiKey)}`);
      this.upstream = socket;
      socket.addEventListener('open', () => {
        this.connecting = false;
        socket.send(JSON.stringify({ action: 'subscribe', params: { symbols: 'XAU/USD' } }));
      });
      socket.addEventListener('message', event => {
        this.ctx.waitUntil(this.handleProviderMessage(event.data));
      });
      socket.addEventListener('error', () => {
        this.broadcast({ event:'error', message:'live_provider_error' });
      });
      socket.addEventListener('close', event => {
        if (this.upstream === socket) this.upstream = null;
        this.connecting = false;
        console.log(JSON.stringify({ message:'central live provider closed', provider:'twelve-data', code:event.code }));
        this.ctx.waitUntil(this.ctx.storage.setAlarm(Date.now() + 5000));
      });
      await this.ctx.storage.setAlarm(Date.now() + 60_000);
      return true;
    } catch (error) {
      this.connecting = false;
      this.upstream = null;
      await this.ctx.storage.setAlarm(Date.now() + 5000);
      console.error(JSON.stringify({ message:'central live provider connect failed', error:error instanceof Error ? error.message : String(error) }));
      return false;
    }
  }

  async handleProviderMessage(raw) {
    const message = normalizeTwelveDataMessage(raw);
    if (!message) return;
    if (message.event !== 'price') {
      this.broadcast(message);
      return;
    }

    const minute = bucket(message.ts, 1);
    const previous = this.currentBar;
    if (!previous || previous.t !== minute) {
      if (previous && previous.t < minute) await this.persistCompletedBar(previous);
      this.currentBar = {
        t: minute, o: message.price, h: message.price, l: message.price,
        c: message.price, v: 1, provider: 'twelve-data'
      };
    } else {
      this.currentBar = {
        ...previous,
        h: Math.max(previous.h, message.price),
        l: Math.min(previous.l, message.price),
        c: message.price,
        v: Number(previous.v || 0) + 1,
        provider: 'twelve-data'
      };
    }
    this.latestQuote = message;
    this.tickHistory = appendTickHistory(this.tickHistory, message);

    const now = Date.now();
    if (now - this.lastSnapshotWriteAt >= 15_000) {
      await this.ctx.storage.put({
        latestQuote:this.latestQuote,
        currentBar:this.currentBar,
        tickHistory:this.tickHistory
      });
      this.lastSnapshotWriteAt = now;
    }
    this.broadcast(message);
  }

  async persistCompletedBar(bar) {
    if (!this.env.GSX_DB || !bar || !Number.isFinite(bar.t)) return;
    if (!this.schemaReady) {
      await maybeEnsureD1(this.env);
      this.schemaReady = true;
    }
    await upsertCompletedBarRollups(this.env,bar);
  }

  broadcast(message) {
    const payload = JSON.stringify(message);
    for (const socket of this.ctx.getWebSockets()) {
      try { socket.send(payload); } catch {}
    }
  }

  async alarm() {
    await this.ensureProvider();
    await this.ctx.storage.setAlarm(Date.now() + 60_000);
  }

  webSocketMessage(socket, message) {
    if (message === 'status' && this.latestQuote) socket.send(JSON.stringify(this.latestQuote));
  }
  webSocketClose(socket, code, reason) {
    try { socket.close(code || 1000, reason || 'closed'); } catch {}
  }
  webSocketError(socket) {
    try { socket.close(1011, 'client error'); } catch {}
  }
}

